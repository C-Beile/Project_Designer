/// Schreibt `bindings.ts` neu (nur im Debug-Build, beim Start). Unit-Tests der Tauri-Hülle laufen unter Windows nicht
/// (fehlendes Manifest, STATUS_ENTRYPOINT_NOT_FOUND), darum entsteht die Datei hier statt in einem Test.
#[cfg(debug_assertions)]
pub fn export_bindings() {
    let file = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../ui/src/api/bindings.ts");
    if let Err(e) = builder().export(specta_typescript::Typescript::default(), &file) {
        eprintln!("bindings.ts konnte nicht geschrieben werden: {e}");
        log::warn!("bindings.ts konnte nicht geschrieben werden: {e}");
    }
}
