// Execute SQL window (manual chapter 8, screenshot 088): connection row, icon bar, statement
// editor, one result tab per executed statement with the middle bar (add/delete/save/cancel/
// truncate/refresh, Max. rows, Fetched Rows, Matching Rows). Reading is the default; every
// writing statement - typed or generated by the grid - needs the explicit switch and a
// confirmation of the concrete statements. The backend enforces the same rule.

const READING = /^\s*(select|show|describe|desc|explain)\b/i

export function looksReadOnly(sql: string): boolean {
  const withoutComments = sql.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/(^|\n)\s*(--|#)[^\n]*/g, '$1')
  return READING.test(withoutComments)
}

const MAX_ROWS_CHOICES = [100, 250, 500, 1000]

interface ResultTab {
  id: number
  sql: string
  result: SqlResult | null
  error: string | null
}

interface Pending {
  statements: string[]
  after: 'run' | 'grid'
}

function Btn({ label, title, onClick, disabled, pressed, children }: { label: string; title?: string; onClick?: () => void; disabled?: boolean; pressed?: boolean; children: ReactNode }) {
  return (
    <button type="button" className="forge-sql-ibtn" aria-label={label} title={title ?? label} aria-pressed={pressed} disabled={disabled} onClick={onClick}>
      {children}
    </button>
  )
}

export function SqlEditor({
  api,
  db,
  label,
  initial,
  onTextChange,
}: {
  api: ForgeApi
  db: DbStatus
  label: string
  initial: string
  onTextChange: (text: string) => void
}) {
  const handle = useRef<MonacoTextHandle | null>(null)
  const nextTab = useRef(1)
  const [writeEnabled, setWriteEnabled] = useState(false)
  const [pending, setPending] = useState<Pending | null>(null)
  const [running, setRunning] = useState(false)
  const [tabs, setTabs] = useState<ResultTab[]>([])
  const [activeTab, setActiveTab] = useState<number | null>(null)
  const [keepPrior, setKeepPrior] = useState(false)
  const [maxRows, setMaxRows] = useState(100)
  const [history, setHistory] = useState<string[] | null>(null)
  const gridRun = useRef<(() => Promise<void>) | null>(null)

  const shared = useTunnelState()
  const sessions = Object.entries(shared.bySystem)
    .filter(([k, v]) => k !== '' && v.connected && !/_bg$/i.test(systemNameOf(k.split('|alias:')[0])))
    .map(([k, v]) => {
      const i = k.indexOf('|alias:')
      const system = systemNameOf(i < 0 ? k : k.slice(0, i))
      return { key: k, label: `${system} · ${i < 0 ? 'System_alias' : k.slice(i + 7)} - ${v.database ?? ''} @ ${v.host ?? ''}` }
    })
    .sort((a, b) => a.label.localeCompare(b.label))
  const activeKey = shared.connectedSystem && sessions.some((s) => s.key === shared.connectedSystem) ? shared.connectedSystem : ''
  async function switchSession(key: string) {
    await api.dbActivate(key).catch(() => false)
    setSystemsDb(await api.dbSystems().catch(() => []))
  }
  const connectionLabel = db.connected ? `${db.database ?? ''} @ ${db.host ?? ''}` : ''

  async function runStatements(statements: string[], allowWrite: boolean) {
    setRunning(true)
    setPending(null)
    const fresh: ResultTab[] = []
    for (const sql of statements) {
      try {
        const result = await api.dbQuery(sql, allowWrite)
        fresh.push({ id: nextTab.current++, sql, result, error: null })
        pushSqlHistory(sql)
        const secs = (result.elapsed_ms / 1000).toFixed(3)
        logOutput('database', `[1:1] Executed successfully in ${secs} s.`)
        if (result.columns.length > 0) logOutput('database', 'Fetching resultset took 0 s.')
        logOutput('database', `Execution finished after ${secs} s, no errors occurred. (${oneLine(sql)})`)
      } catch (e) {
        const message = e instanceof Error ? e.message : String(e)
        fresh.push({ id: nextTab.current++, sql, result: null, error: message })
        logOutput('database', '[1:1] Failed in 0 s.', 'error')
        logOutput('database', `[Exception] ${message}`, 'error')
        logOutput('database', '  Line 1, column 1', 'error')
        logOutput('database', `Execution finished after 0 s, 1 error occurred. (${oneLine(sql)})`, 'error')
        break
      }
    }
    setTabs((prev) => (keepPrior ? [...prev, ...fresh] : fresh))
    if (fresh.length) setActiveTab(fresh[fresh.length - 1].id)
    setRunning(false)
  }

  function start(statements: string[]) {
    if (statements.length === 0 || running) return
    if (writeEnabled && statements.some((s) => !looksReadOnly(s))) {
      setPending({ statements, after: 'run' })
      return
    }
    void runStatements(statements, false)
  }

  function runAll() {
    const sel = handle.current?.getSelection()
    const text = sel && sel.text.trim() ? sel.text : (handle.current?.getValue() ?? '')
    start(splitStatements(text).map((s) => s.text))
  }

  function runStatement() {
    const sel = handle.current?.getSelection()
    if (sel && sel.text.trim()) {
      start([sel.text.trim()])
      return
    }
    const text = handle.current?.getValue() ?? ''
    const hit = statementAt(text, handle.current?.getCursorOffset() ?? 0)
    if (hit) start([hit.text])
  }

  function onKeyDownCapture(e: KeyboardEvent<HTMLDivElement>) {
    if ((e.ctrlKey || e.metaKey) && e.key === 'Enter') {
      e.preventDefault()
      e.stopPropagation()
      if (e.shiftKey) runStatement()
      else runAll()
    }
  }

  function action(id: string) {
    handle.current?.runAction(id)
    handle.current?.focus()
  }

  function closeTab(id: number) {
    setTabs((prev) => {
      const next = prev.filter((t) => t.id !== id)
      if (activeTab === id) setActiveTab(next.length ? next[next.length - 1].id : null)
      return next
    })
  }

  function openHistory() {
    setHistory(history ? null : loadSqlHistory())
  }

  const active = tabs.find((t) => t.id === activeTab) ?? null
  const noConnection = !db.connected

  return (
    <div className="forge-sql" onKeyDownCapture={onKeyDownCapture}>
      <div className="forge-sql-conn-row">
        <label>
          <span>Connection:</span>
          {sessions.length > 1 ? (
            <select aria-label="Connection" value={activeKey} disabled={!db.connected} onChange={(e) => void switchSession(e.target.value)}>
              {activeKey === '' ? <option value="">{connectionLabel}</option> : null}
              {sessions.map((s) => (
                <option key={s.key} value={s.key}>
                  {s.label}
                </option>
              ))}
            </select>
          ) : (
            <select aria-label="Connection" value={db.connected ? 'current' : ''} disabled={!db.connected} onChange={() => {}}>
              {db.connected ? <option value="current">{connectionLabel}</option> : <option value="">&lt;not connected&gt;</option>}
            </select>
          )}
        </label>
        <label className="forge-sql-write">
          <input
            type="checkbox"
            checked={writeEnabled}
            onChange={(e) => {
              setWriteEnabled(e.target.checked)
              setPending(null)
            }}
          />
          <span>Allow write statements</span>
        </label>
      </div>
      <div className="forge-sql-toolbar" role="toolbar" aria-label="SQL toolbar">
        <Btn label="Run" title="run sql - executes all statements, or the marked text (Ctrl+Enter)" onClick={runAll} disabled={noConnection || running}>
          <span className="forge-sql-glyph forge-sql-run">▶▶</span>
        </Btn>
        <Btn label="Run selected statement" title="run statement - the marked statement or the one at the cursor (Ctrl+Shift+Enter)" onClick={runStatement} disabled={noConnection || running}>
          <span className="forge-sql-glyph forge-sql-run">▶</span>
        </Btn>
        <Btn label="Connection services" title="connection services - opens the Services window" onClick={() => requestShell('services')}>
          <span className="forge-sql-glyph">⛁</span>
        </Btn>
        <span className="forge-sql-sep" aria-hidden="true" />
        <Btn label="SQL history" title="sql history" onClick={openHistory}>
          <span className="forge-sql-glyph">☰</span>
        </Btn>
        <Btn label="Keep prior tabs" title="prior tabs - keep the result tabs of earlier runs" pressed={keepPrior} onClick={() => setKeepPrior((v) => !v)}>
          <span className="forge-sql-glyph">❐</span>
        </Btn>
        <Btn label="Last edit" title="last edit - not available in this editor" disabled>
          <span className="forge-sql-glyph">✎</span>
        </Btn>
        <Btn label="Back" title="back" onClick={() => action('cursorUndo')}>
          <span className="forge-sql-glyph">◀</span>
        </Btn>
        <Btn label="Forward" title="forward" onClick={() => action('cursorRedo')}>
          <span className="forge-sql-glyph">▷</span>
        </Btn>
        <span className="forge-sql-sep" aria-hidden="true" />
        <Btn label="Find" title="find (Ctrl+F)" onClick={() => action('actions.find')}>
          <span className="forge-sql-glyph">⌕</span>
        </Btn>
        <Btn label="Previous find" title="previous find" onClick={() => action('editor.action.previousMatchFindAction')}>
          <span className="forge-sql-glyph">↖</span>
        </Btn>
        <Btn label="Next find" title="next find" onClick={() => action('editor.action.nextMatchFindAction')}>
          <span className="forge-sql-glyph">↘</span>
        </Btn>
        <Btn label="Highlight search" title="highlight search - always on in this editor" disabled>
          <span className="forge-sql-glyph">▨</span>
        </Btn>
        <Btn label="Rectangular search" title="rectangular search - not available in this editor" disabled>
          <span className="forge-sql-glyph">▢</span>
        </Btn>
        <span className="forge-sql-sep" aria-hidden="true" />
        <Btn label="Previous bookmark" title="previous bookmark - not available yet" disabled>
          <span className="forge-sql-glyph">⇡</span>
        </Btn>
        <Btn label="Next bookmark" title="next bookmark - not available yet" disabled>
          <span className="forge-sql-glyph">⇣</span>
        </Btn>
        <Btn label="Toggle bookmark" title="toggle bookmark - not available yet" disabled>
          <span className="forge-sql-glyph">⚑</span>
        </Btn>
        <span className="forge-sql-sep" aria-hidden="true" />
        <Btn label="Left shift" title="left shift" onClick={() => action('editor.action.outdentLines')}>
          <span className="forge-sql-glyph">⇤</span>
        </Btn>
        <Btn label="Right shift" title="right shift" onClick={() => action('editor.action.indentLines')}>
          <span className="forge-sql-glyph">⇥</span>
        </Btn>
        <span className="forge-sql-sep" aria-hidden="true" />
        <Btn label="Start macro" title="start macros - macro execution is not supported by the Designer" disabled>
          <span className="forge-sql-glyph">●</span>
        </Btn>
        <Btn label="Stop macro" title="stop macros - macro execution is not supported by the Designer" disabled>
          <span className="forge-sql-glyph">■</span>
        </Btn>
        <span className="forge-sql-sep" aria-hidden="true" />
        <Btn label="Comment" title="comment (Ctrl+/)" onClick={() => action('editor.action.addCommentLine')}>
          <span className="forge-sql-glyph">//</span>
        </Btn>
        <Btn label="Uncomment" title="uncomment" onClick={() => action('editor.action.removeCommentLine')}>
          <span className="forge-sql-glyph">/-</span>
        </Btn>
      </div>
      <div className="forge-sql-editor">
        <MonacoText initial={initial} language="sql" readOnly={false} label={label} onChange={onTextChange} handleRef={handle} />
        {history ? (
          <div className="forge-sql-history" role="dialog" aria-label="SQL history">
            <div className="forge-sql-history-head">
              <strong>SQL history</strong>
              <button
                type="button"
                onClick={() => {
                  clearSqlHistory()
                  setHistory([])
                }}
              >
                Clear
              </button>
              <button type="button" onClick={() => setHistory(null)}>
                Close
              </button>
            </div>
            {history.length === 0 ? <p className="forge-field-hint">No statements executed yet.</p> : null}
            <ul>
              {history.map((h) => (
                <li key={h}>
                  <button
                    type="button"
                    title={h}
                    onClick={() => {
                      const current = handle.current?.getValue() ?? ''
                      handle.current?.setValue(current.trim() ? `${current.replace(/\s+$/, '')}\n${h}` : h)
                      onTextChange(handle.current?.getValue() ?? h)
                      setHistory(null)
                    }}
                  >
                    {oneLine(h)}
                  </button>
                </li>
              ))}
            </ul>
          </div>
        ) : null}
      </div>
      {pending !== null ? (
        <div className="forge-sql-confirm" role="alertdialog" aria-label="Confirm write statement">
          <p>
            {pending.statements.length === 1 ? 'This statement can change data in the database. Run it?' : `These ${pending.statements.length} statements can change data in the database. Run them?`}
          </p>
          <pre>{pending.statements.join(';\n')}</pre>
          <button
            type="button"
            onClick={() => {
              if (pending.after === 'grid') void gridRun.current?.()
              else void runStatements(pending.statements, true)
            }}
          >
            {pending.statements.length === 1 ? 'Run statement' : `Run ${pending.statements.length} statements`}
          </button>
          <button type="button" onClick={() => setPending(null)}>
            Cancel
          </button>
        </div>
      ) : null}
      <div className="forge-sql-result">
        {noConnection && tabs.length === 0 ? <p className="forge-field-hint">Connect in the Services tab first.</p> : null}
        {tabs.length > 0 ? (
          <div className="forge-sql-tabs" role="tablist" aria-label="Statement results">
            {tabs.map((t) => (
              <span key={t.id} className={`forge-sql-tab${t.id === activeTab ? ' is-active' : ''}${t.error ? ' is-error' : ''}`}>
                <button type="button" role="tab" aria-selected={t.id === activeTab} title={t.sql} onClick={() => setActiveTab(t.id)}>
                  {oneLine(t.sql, 40)}
                </button>
                <button type="button" aria-label={`Close result ${oneLine(t.sql, 20)}`} onClick={() => closeTab(t.id)}>
                  ×
                </button>
              </span>
            ))}
          </div>
        ) : null}
        {active ? (
          <ResultPane
            key={active.id}
            tab={active}
            api={api}
            maxRows={maxRows}
            onMaxRows={setMaxRows}
            writeEnabled={writeEnabled}
            running={running}
            connected={!noConnection}
            onAskConfirm={(statements, run) => {
              gridRun.current = run
              setPending({ statements, after: 'grid' })
            }}
            onClosePending={() => setPending(null)}
            onRefresh={async () => {
              await runStatements([active.sql], false)
            }}
          />
        ) : null}
      </div>
    </div>
  )
}

function oneLine(sql: string, max = 120): string {
  const flat = sql.replace(/\s+/g, ' ').trim()
  return flat.length > max ? `${flat.slice(0, max - 1)}…` : flat
}

type Row = (string | null)[]

function ResultPane({
  tab,
  api,
  maxRows,
  onMaxRows,
  writeEnabled,
  running,
  connected,
  onAskConfirm,
  onClosePending,
  onRefresh,
}: {
  tab: ResultTab
  api: ForgeApi
  maxRows: number
  onMaxRows: (n: number) => void
  writeEnabled: boolean
  running: boolean
  connected: boolean
  onAskConfirm: (statements: string[], run: () => Promise<void>) => void
  onClosePending: () => void
  onRefresh: () => Promise<void>
}) {
  const result = tab.result
  const table = useMemo(() => editableTable(tab.sql), [tab.sql])
  const [filter, setFilter] = useState('')
  const [selected, setSelected] = useState<number | null>(null)
  const [sort, setSort] = useState<{ col: number; dir: 1 | -1 } | null>(null)
  const [edits, setEdits] = useState<Map<number, Row>>(new Map())
  const [removed, setRemoved] = useState<Set<number>>(new Set())
  const [added, setAdded] = useState<Row[]>([])
  const [cell, setCell] = useState<{ row: number; col: number } | null>(null)
  const [message, setMessage] = useState<string | null>(null)
  const editable = Boolean(table && result && result.columns.length > 0)
  const [cellMenu, setCellMenu] = useState<{ x: number; y: number; row: (string | null)[]; col: number; index: number } | null>(null)

  useEffect(() => {
    setSelected(null)
  }, [filter, sort])

  if (tab.error) {
    return (
      <p className="forge-field-error" role="alert">
        {tab.error}
      </p>
    )
  }
  if (!result) return null
  if (result.columns.length === 0) {
    return (
      <p className="forge-field-hint" data-testid="sql-summary">
        Statement executed.
      </p>
    )
  }

  const columns = result.columns
  const shownRows = result.rows.slice(0, maxRows)
  type View = { index: number; row: Row; isNew: boolean }
  let view: View[] = [
    ...shownRows.map((r, i) => ({ index: i, row: edits.get(i) ?? r, isNew: false })).filter((v) => !removed.has(v.index)),
    ...added.map((r, i) => ({ index: -1 - i, row: r, isNew: true })),
  ]
  view = view.filter((v) => matchesFilter(v.row, filter))
  if (sort) {
    const { col, dir } = sort
    view = [...view].sort((a, b) => {
      const x = a.row[col]
      const y = b.row[col]
      if (x === y) return 0
      if (x === null) return -dir
      if (y === null) return dir
      const nx = Number(x)
      const ny = Number(y)
      return (Number.isFinite(nx) && Number.isFinite(ny) && x.trim() !== '' && y.trim() !== '' ? nx - ny : x.localeCompare(y)) * dir
    })
  }
  const dirty = edits.size > 0 || removed.size > 0 || added.length > 0
  const guard = !writeEnabled ? 'Switch on "Allow write statements" to edit the result' : !editable ? 'Only a plain select from one table can be edited' : undefined

  function cancelEdits() {
    setEdits(new Map())
    setRemoved(new Set())
    setAdded([])
    setCell(null)
    setMessage(null)
  }

  function commit(r: SqlResult, t: string) {
    const statements: string[] = []
    r.rows.slice(0, maxRows).forEach((orig, i) => {
      if (removed.has(i)) statements.push(buildDelete(t, r.columns, orig))
      else if (edits.has(i)) {
        const sql = buildUpdate(t, r.columns, orig, edits.get(i)!)
        if (sql) statements.push(sql)
      }
    })
    for (const row of added) statements.push(buildInsert(t, r.columns, row))
    if (statements.length === 0) {
      setMessage('Nothing to save.')
      return
    }
    onAskConfirm(statements, async () => {
      onClosePending()
      try {
        for (const s of statements) {
          await api.dbQuery(s, true)
          logOutput('database', `SQL OK: ${oneLine(s)}`)
        }
        cancelEdits()
        setMessage(`${statements.length} change(s) committed.`)
        await onRefresh()
      } catch (e) {
        const msg = e instanceof Error ? e.message : String(e)
        logOutput('database', `SQL FAILED: ${msg}`, 'error')
        setMessage(`Saving stopped: ${msg}`)
      }
    })
  }

  function truncate(t: string) {
    onAskConfirm([`TRUNCATE TABLE ${t}`], async () => {
      onClosePending()
      try {
        await api.dbQuery(`TRUNCATE TABLE ${t}`, true)
        logOutput('database', `SQL OK: TRUNCATE TABLE ${t}`)
        await onRefresh()
      } catch (e) {
        setMessage(e instanceof Error ? e.message : String(e))
      }
    })
  }

  function exportCsv() {
    const csv = toCsv(columns, view.map((v) => v.row), getOptions().misc.csvSeparator)
    try {
      const url = URL.createObjectURL(new Blob([`﻿${csv}`], { type: 'text/csv;charset=utf-8' }))
      const a = document.createElement('a')
      a.href = url
      a.download = `${table ?? 'result'}.csv`
      document.body.appendChild(a)
      a.click()
      a.remove()
      setTimeout(() => URL.revokeObjectURL(url), 1000)
    } catch (e) {
      setMessage(`Export failed: ${e instanceof Error ? e.message : String(e)}`)
    }
  }

  async function copyCsv() {
    try {
      await navigator.clipboard.writeText(toCsv(columns, view.map((v) => v.row), '\t'))
      setMessage('Result copied to the clipboard (tab separated).')
    } catch {
      setMessage('The clipboard is not available.')
    }
  }

  function setCellValue(v: View, col: number, value: string | null) {
    if (v.isNew) {
      setAdded((prev) => prev.map((r, i) => (i === -1 - v.index ? r.map((c, ci) => (ci === col ? value : c)) : r)))
    } else {
      const base = edits.get(v.index) ?? result!.rows[v.index]
      setEdits((prev) => new Map(prev).set(v.index, base.map((c, ci) => (ci === col ? value : c))))
    }
  }

  const sel = view.find((v) => v.index === selected) ?? null
  return (
    <>
      <div className="forge-sql-midbar" role="toolbar" aria-label="Result toolbar">
        <Btn label="Add row" title={guard ?? 'add row'} disabled={!!guard} onClick={() => setAdded((p) => [...p, columns.map(() => null)])}>
          <span className="forge-sql-glyph">＋</span>
        </Btn>
        <Btn
          label="Delete row"
          title={guard ?? 'delete row'}
          disabled={!!guard || !sel}
          onClick={() => {
            if (!sel) return
            if (sel.isNew) setAdded((p) => p.filter((_, i) => i !== -1 - sel.index))
            else setRemoved((p) => new Set(p).add(sel.index))
            setSelected(null)
          }}
        >
          <span className="forge-sql-glyph">－</span>
        </Btn>
        <Btn label="Save row" title={guard ?? 'save row - commits the edits to the database, cannot be rolled back'} disabled={!!guard || !dirty} onClick={() => table && commit(result, table)}>
          <span className="forge-sql-glyph">✔</span>
        </Btn>
        <Btn label="Cancel edits" title="cancel edits" disabled={!dirty} onClick={cancelEdits}>
          <span className="forge-sql-glyph">✖</span>
        </Btn>
        <Btn label="Truncate table" title={guard ?? 'truncate table - deletes all rows without logging'} disabled={!!guard} onClick={() => table && truncate(table)}>
          <span className="forge-sql-glyph forge-sql-danger">⌫</span>
        </Btn>
        <Btn label="Refresh" title="refresh" disabled={!connected || running} onClick={() => void onRefresh()}>
          <span className="forge-sql-glyph">↻</span>
        </Btn>
        <label className="forge-sql-mid-field">
          <span>Max. rows:</span>
          <select aria-label="Max. rows" value={maxRows} onChange={(e) => onMaxRows(Number(e.target.value))}>
            {MAX_ROWS_CHOICES.map((n) => (
              <option key={n} value={n}>
                {n}
              </option>
            ))}
          </select>
        </label>
        <span className="forge-sql-mid-field" data-testid="sql-summary">
          Fetched Rows: <strong>{shownRows.length}</strong>
          {result.rows.length > shownRows.length || result.truncated ? ' (more available)' : ''}
          <span className="forge-field-hint"> · {result.elapsed_ms} ms</span>
        </span>
        <Btn label="Export CSV" title="export the shown rows as a CSV file" onClick={exportCsv}>
          <span className="forge-sql-glyph">⭳</span>
        </Btn>
        <Btn label="Copy result" title="copy the shown rows to the clipboard" onClick={() => void copyCsv()}>
          <span className="forge-sql-glyph">⧉</span>
        </Btn>
        <label className="forge-sql-mid-field forge-sql-matching">
          <span>Matching Rows:</span>
          <input type="text" aria-label="Matching Rows" value={filter} onChange={(e) => setFilter(e.target.value)} />
        </label>
      </div>
      {message ? <p className="forge-field-hint">{message}</p> : null}
      <div className="forge-sql-grid">
        <table aria-label="Query result">
          <thead>
            <tr>
              <th className="forge-sql-rownum">#</th>
              {columns.map((c, i) => (
                <th key={i} onClick={() => setSort((s) => (s && s.col === i ? (s.dir === 1 ? { col: i, dir: -1 } : null) : { col: i, dir: 1 }))} title="click to sort">
                  {c}
                  {sort?.col === i ? (sort.dir === 1 ? ' ▲' : ' ▼') : ''}
                </th>
              ))}
            </tr>
          </thead>
          <tbody>
            {view.map((v, n) => (
              <tr key={v.index} className={`${v.index === selected ? 'is-selected' : ''}${v.isNew ? ' is-new' : ''}`} onClick={() => setSelected(v.index)}>
                <td className="forge-sql-rownum">{n + 1}</td>
                {v.row.map((value, c) => {
                  const editing = cell && cell.row === v.index && cell.col === c
                  return (
                    <td
                      key={c}
                      className={`${value === null ? 'is-null' : ''}${!v.isNew && edits.get(v.index) && edits.get(v.index)![c] !== result.rows[v.index][c] ? ' is-edited' : ''}`}
                      onDoubleClick={() => {
                        if (!guard) setCell({ row: v.index, col: c })
                      }}
                      onContextMenu={(e) => {
                        e.preventDefault()
                        setSelected(v.index)
                        setCellMenu({ x: e.clientX, y: e.clientY, row: v.row, col: c, index: v.index })
                      }}
                    >
                      {editing ? (
                        <input
                          autoFocus
                          aria-label={`Edit ${columns[c]}`}
                          defaultValue={value ?? ''}
                          onBlur={(e) => {
                            setCellValue(v, c, e.target.value === '' && value === null ? null : e.target.value)
                            setCell(null)
                          }}
                          onKeyDown={(e) => {
                            if (e.key === 'Enter') (e.target as HTMLInputElement).blur()
                            if (e.key === 'Escape') setCell(null)
                          }}
                        />
                      ) : value === null ? (
                        'NULL'
                      ) : (
                        value
                      )}
                    </td>
                  )
                })}
              </tr>
            ))}
          </tbody>
        </table>
      </div>
      {cellMenu ? (
        <TreeContextMenu
          entries={[
            { id: 'cell', label: 'Copy Cell', enabled: true },
            { id: 'row', label: 'Copy Row', enabled: true },
            { id: 'result', label: 'Copy Result', enabled: true },
            { id: 'csv', label: 'Export CSV', enabled: true },
            { id: 'sep', label: '', enabled: false, separator: true },
            { id: 'edit', label: 'Edit Cell', enabled: !guard, hint: guard },
          ]}
          x={cellMenu.x}
          y={cellMenu.y}
          onPick={(id) => {
            if (id === 'cell') void navigator.clipboard?.writeText(cellMenu.row[cellMenu.col] ?? '')
            else if (id === 'row') void navigator.clipboard?.writeText(cellMenu.row.map((v) => v ?? '').join('\t'))
            else if (id === 'result') void copyCsv()
            else if (id === 'csv') exportCsv()
            else if (id === 'edit') setCell({ row: cellMenu.index, col: cellMenu.col })
          }}
          onClose={() => setCellMenu(null)}
        />
      ) : null}
    </>
  )
}
