// Generates app/ui/src/properties/sheetModel.generated.ts and propertyDescriptions.generated.ts from
// the specification JSONs (60_design/designer_gui/sheet_model.json and properties.json).
// Run: node scripts/gen-sheet-model.mjs   (from the forge folder)

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const specDir = resolve(here, '../../../60_design/designer_gui')
const outDir = resolve(here, '../app/ui/src/properties')

const sheet = JSON.parse(readFileSync(resolve(specDir, 'sheet_model.json'), 'utf8'))
const described = JSON.parse(readFileSync(resolve(specDir, 'properties.json'), 'utf8')).objects

// SheetTab in enum order: id, parent, EN title, DE title (DESIGNER_BEHAVIOR_SPEC.md 3.1).
const TABS = [
  ['PROPERTIES', null, 'Properties', 'Eigenschaften'],
  ['LAYOUT', null, 'Layout', 'Layout'],
  ['OTHERS', null, 'Others', 'Andere'],
  ['EXTENDED', null, 'Extended', 'Erweitert'],
  ['INTERNAL', null, 'Internal', 'Intern'],
  ['DYNAMIC_TAB', null, 'Dynamic', 'Dynamisch'],
  ['RECORDCONTAINER', null, 'Source', 'Quelle'],
  ['SYSTEM', null, 'System', 'System'],
  ['WEBSERVICES', 'SYSTEM', 'Web services', 'Webservices'],
  ['CLIENT', 'SYSTEM', 'Client', 'Client'],
  ['LOGIN', 'SYSTEM', 'Login', 'Login'],
  ['SECURITY', 'SYSTEM', 'Security', 'Sicherheit'],
  ['MODULES', null, 'Modules', 'Modules'],
  ['DATABASE', 'MODULES', 'Database', 'Database'],
  ['CALENDAR', 'MODULES', 'Calendar', 'Calendar'],
  ['EMAIL', 'MODULES', 'Email', 'EMail'],
  ['INDEXSEARCH', 'MODULES', 'Indexsearch', 'Indexsuche'],
  ['NOTIFICATIONCENTER', 'MODULES', 'Notifications', 'Benachrichtigungen'],
  ['JLOADR', 'MODULES', 'JLoadr', 'JLoadr'],
  ['TELEMETRY', 'MODULES', 'Monitoring', 'Monitoring'],
  ['DASHLETSTORE', 'MODULES', 'Dashlet Store', 'Dashlet Store'],
  ['USERDIRECTORY', 'MODULES', 'Userdirectory', 'Benutzerverzeichnis'],
  ['LOGGING', null, 'Logging', 'Logging'],
  ['CUSTOM', null, 'Custom', 'Benutzerdefiniert'],
  ['CUSTOM_PREFERENCES', 'CUSTOM', '_____PREFERENCES_PROJECT', '_____PREFERENCES_PROJECT'],
  ['CUSTOM_CONFIG', 'CUSTOM', '_____CONFIGURATION', '_____CONFIGURATION'],
  ['NOVA_COMMUNICATION', null, 'Nova Communication', 'Nova Communication'],
  ['SERVICES', null, 'Services', 'Services'],
  ['NATS_SERVICE', 'SERVICES', 'NATS', 'NATS'],
  ['JWT_SERVICE', 'SERVICES', 'JWT', 'JWT'],
]

// SheetTabCategory: the 18 constants of DESIGNER_BEHAVIOR_SPEC.md 3.2 in enum order (with titles), then the
// remaining constants alphabetically. The order of the rest inside one tab is NOT evidenced.
const CATEGORY_TITLES = [
  ['GENERAL', 'General', 'Allgemein'],
  ['PARENT', 'Parent', 'Parent'],
  ['DATABASEFIELD', 'Database column', 'Datenbankfeld'],
  ['FILE_ASSIGNMENT', 'File assignment', 'Dateizuordnung'],
  ['POSITION_SIZE', 'Position / Size', 'Position / Größe'],
  ['DYNAMIC', 'Dynamics', 'Dynamik'],
  ['CAPTION', 'Caption', 'Beschriftung'],
  ['BACKGROUND_COLOR', 'Background colour', 'Hintergrund Farbe'],
  ['USERHELP', 'Userhelp', 'Userhilfe'],
  ['DATABASE', 'Database', 'Datenbank'],
  ['MSTEAMS', 'MSTeams', 'MSTeams'],
  ['ENTITY', 'Entity', 'Entity'],
  ['RENDERING', 'Renderer Mapping', 'Renderer Mapping'],
  ['FIELDS', 'Fields', 'Felder'],
  ['FAVORITE', 'Favorite Fields', 'Favorite Fields'],
  ['ACTIONS', 'Actions', 'Aktionen'],
  ['VIEWS', 'Views', 'Views'],
  ['LABEL', 'Label', 'Label'],
]

const humanize = (id) =>
  id
    .split('_')
    .map((w) => (w.length <= 3 && /^[A-Z0-9]+$/.test(w) && !['AND', 'THE'].includes(w) ? w : w.charAt(0) + w.slice(1).toLowerCase()))
    .join(' ')

const used = new Set()
const models = {}
const descriptions = {}
let propCount = 0
let described_count = 0

for (const [model, entry] of Object.entries(sheet)) {
  const props = []
  for (const p of entry.properties) {
    const tab = p.sheetTab ?? 'PROPERTIES'
    const category = p.sheetTabCategory ?? 'GENERAL'
    used.add(category)
    const owner = p.defined_in ?? model
    const text = p.desc ?? described[owner]?.[p.name] ?? described[model]?.[p.name]
    if (text) {
      descriptions[`${owner}.${p.name}`] = text
      described_count++
    }
    props.push([p.name, tab, category, Number.parseInt(p.position ?? '0', 10) || 0, p.type ?? 'NETBEANS', p.optional === 'true' ? 1 : 0, owner])
    propCount++
  }
  models[model] = { id: entry.model_type_id, supertypes: entry.supertypes, props }
}

const known = new Set(CATEGORY_TITLES.map((c) => c[0]))
const rest = [...used].filter((c) => !known.has(c)).sort()
const categories = [...CATEGORY_TITLES, ...rest.map((c) => [c, humanize(c), humanize(c)])]

const header = '// Generated by scripts/gen-sheet-model.mjs from designer_gui/sheet_model.json and properties.json. Do not edit.\n'
const out =
  header +
  `export const SHEET_TABS: readonly (readonly [string, string | null, string, string])[] = ${JSON.stringify(TABS)}\n\n` +
  `export const SHEET_CATEGORIES: readonly (readonly [string, string, string])[] = ${JSON.stringify(categories)}\n\n` +
  '// [name, tab, category, position, editor type, optional, defined in]\n' +
  'export type SheetModelProp = readonly [string, string, string, number, string, 0 | 1, string]\n\n' +
  'export interface SheetModelEntry {\n  id: number\n  supertypes: readonly string[]\n  props: readonly SheetModelProp[]\n}\n\n' +
  `export const SHEET_MODELS: Readonly<Record<string, SheetModelEntry>> = ${JSON.stringify(models)}\n`
writeFileSync(resolve(outDir, 'sheetModel.generated.ts'), out)

const descOut = header + `export const PROPERTY_DESCRIPTIONS: Readonly<Record<string, string>> = ${JSON.stringify(descriptions)}\n`
writeFileSync(resolve(outDir, 'propertyDescriptions.generated.ts'), descOut)

console.log(`${Object.keys(models).length} model types, ${propCount} properties, ${described_count} described, ${categories.length} categories`)
